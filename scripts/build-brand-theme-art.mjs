// Keep exported SVG previews self-contained and preserve PNG support for email.
import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {BRAND_THEME_VERSIONS} from '../src/brand-theme-versions.mjs';
const assets=new URL('../admin-site/assets/brand-themes/',import.meta.url);
const images={};
for(const key of ['football','christmas','easter','summer']){
  const version=BRAND_THEME_VERSIONS[key];
  const source=fileURLToPath(new URL(`sources/${key}-v${version}.png`,assets));
  for(const extension of ['webp','png']){
    const target=fileURLToPath(new URL(`${key}-v${version}.${extension}`,assets));
    execFileSync('magick',[source,'-resize','480x720','-strip','-quality','85',target]);
  }
  images[key]='data:image/webp;base64,'+(await readFile(new URL(`${key}-v${version}.webp`,assets))).toString('base64');
}
await writeFile(new URL('../src/brand-theme-assets.mjs',import.meta.url),'// Generated by scripts/build-brand-theme-art.mjs.\nexport const BRAND_THEME_ASSETS='+JSON.stringify(images)+';\n');
