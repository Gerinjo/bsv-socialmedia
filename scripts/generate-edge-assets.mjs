import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(rootDir, 'supabase/functions/_shared/story-assets.generated.ts');

const textFiles = {
  announcement: 'templates/announcement.svg',
  lineup: 'templates/lineup.svg',
  result: 'templates/result.svg',
  birthday: 'templates/birthday.svg',
};

const binaryFiles = {
  captureFont: ['brand/fonts/Capture it.ttf', 'font/ttf'],
  notoSansRegular: ['brand/fonts/NotoSans-Regular.ttf', 'font/ttf'],
  notoSansBlack: ['brand/fonts/NotoSans-Black.ttf', 'font/ttf'],
  notoSerifItalic: ['brand/fonts/NotoSerif-Italic.ttf', 'font/ttf'],
};

const templates = Object.fromEntries(await Promise.all(
  Object.entries(textFiles).map(async ([name, path]) => [name, await readFile(resolve(rootDir, path), 'utf8')]),
));

const assets = Object.fromEntries(await Promise.all(
  Object.entries(binaryFiles).map(async ([name, [path, mime]]) => {
    const base64 = (await readFile(resolve(rootDir, path))).toString('base64');
    return [name, { base64, mime }];
  }),
));

const source = [
  '// Generated by npm run build:edge-assets. Do not edit by hand.',
  `export const STORY_TEMPLATES = ${JSON.stringify(templates)} as const;`,
  `export const STORY_ASSETS = ${JSON.stringify(assets)} as const;`,
  '',
].join('\n');

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(`Edge-Assets erzeugt: ${outputPath}`);
